// Imprima todos os números pares de 1 a 20 utilizando um laço de repetição (USANDO O DO WHILE, WHILE E FOR).
// While 
var numero = 2; 

while (numero <= 20) {
  console.log(numero);
  numero += 2; 
} 

// Do while
var num = 2; 
do{
    console.log(num);
num += 2;
} while (num <= 20);


// For
for (var num = 2; num <= 20; num += 2 ){
    console.log(num); 
}
