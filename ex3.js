// Imprima todos os números IMPARES de 1 a 50 utilizando um laço de repetição (USANDO O DO WHILE, WHILE E FOR).

//while 
var num = 1; 

while (num <= 50) {

  console.log(num,);
  num += 2; 
} 

//Do while
let j = 1;

do {
  console.log(j);
  j += 2;
} while (j <= 50); 

//for 
for (let k = 1; k <= 50; k += 2) {
  console.log(k);
}

